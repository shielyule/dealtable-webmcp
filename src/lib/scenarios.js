export function scenarioToDeal(scenario, overrides = {}) {
  return {
    scenario: scenario.id,
    title: scenario.title,
    sessionId: scenario.sessionId,
    unit: scenario.unit,
    currency: scenario.currency,
    targetPrice: overrides.targetPrice ?? scenario.targetPrice,
    walkawayPrice: overrides.walkawayPrice ?? scenario.walkawayPrice,
    currentAsk: overrides.currentAsk ?? scenario.currentAsk,
    termYears: overrides.termYears ?? scenario.termYears,
    maxTermYears: scenario.maxTermYears,
    concessionPct: overrides.concessionPct ?? scenario.concessionPct,
    rigidity: scenario.rigidity,
  }
}

export function getScenario(id) {
  return SCENARIOS[id] ?? SCENARIOS.lease
}

export function getPersona(id) {
  return PERSONAS[id] ?? PERSONAS.aggressive_landlord
}
